package com.pluralsight;

class VariableApp {
    public static void main (String[] args) {
        String favoriteColor = "Royal blue";
        System.out.println("My favorite color is " + favoriteColor);

        int startYear = 2026;
        System.out.println("I started this class in " + startYear);

        char middleInitial = 'N';
        System.out.println("My middle initial is " + middleInitial);

        String hasPets = "Yes";
        System.out.println("Do I have pets? " + hasPets);

        String message = "A quote would be ~Pas a pas, es fa el camí~, which means every flower blooms in its own.";
        System.out.println(message);

        int daysInWeek = 7;
        System.out.println("There are " + daysInWeek + " days in a week.");

        double coffeePrice = 4.99;
        System.out.println("The price of the is $" + coffeePrice + ".");

        char favoriteLetter = 'P';
        System.out.println("My favorite letter is " + favoriteLetter + " because It's my wife's name.");

        boolean isRaining = false;
        System.out.println("Is it raining? " + isRaining);

    }
}
